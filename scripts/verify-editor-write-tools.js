import assert from 'node:assert/strict';
import { createFlowGroupBlock } from '../js/flow-project-model.js';
import { createEditorReadonlyTools } from '../js/editor-readonly-tools.js';
import { createEditorWriteTools } from '../js/editor-write-tools.js';
import { editFlowParagraph } from '../js/flow-paragraph-edit.js';
import { state } from '../js/state.js';
import { pushState, undo, redo, clearHistory } from '../js/history.js';
const make = () => createFlowGroupBlock({ id: 'g', sourceLanguage: 'ja', document: { sourceLanguage: 'ja', sections: [{ id: 's', blocks: [{ id: 'p', type: 'paragraph', texts: { ja: '灯台の光。', 'en-GB': 'A lighthouse.' } }] }] } });
let identity = {}, languageKey = 'ja', busy = false, room = 'editor', activeGroupId = 'g', commits = 0;
state.blocks = [make()]; state.version = 6; clearHistory();
const readState = () => ({ room, workIdentity: identity, blocks: state.blocks, languageKeys: ['ja', 'en-GB', 'en-US'], languageKey, activeGroupId, busy });
const readonly = createEditorReadonlyTools({ readState });
const writer = createEditorWriteTools({ readState, readonly, applyEdit: result => { pushState(); state.blocks = result.blocks; commits++; } });
const read = token => writer.execute('dsf_read_flow_paragraph', { workToken: token, groupId: 'g', sectionId: 's', blockId: 'p', languageKey });
const write = (p, text) => writer.execute('dsf_replace_flow_paragraph', { workToken: p.workToken, editToken: p.editToken, text });
readonly.enable(); const token = readonly.execute('dsf_get_editor_context', {}).workToken;
const before = JSON.stringify(state.blocks), first = read(token);
assert.equal(first.text, '灯台の光。'); assert.equal(JSON.stringify(state.blocks), before);
assert.equal(write(first, '灯台の明かり。').changed, true); assert.equal(commits, 1);
assert.equal(write(first, '灯台の明かり。').replayed, true); assert.equal(commits, 1);
assert.equal(write(first, '別の文。').error.code, 'STALE_EDIT_TOKEN');
undo(() => {}); assert.equal(JSON.stringify(state.blocks), before);
redo(() => {}); assert.equal(state.blocks[0].flow.document.sections[0].blocks[0].texts.ja, '灯台の明かり。');
const unchanged = read(token); assert.equal(write(unchanged, unchanged.text).changed, false); assert.equal(commits, 1);
const stale = read(token); state.blocks[0].flow.document.sections[0].blocks[0].texts.ja = '手入力。';
assert.equal(write(stale, '上書き。').error.code, 'STALE_TEXT'); assert.equal(commits, 1);
const pending = read(token); busy = true; assert.equal(write(pending, '変更').error.code, 'BUSY'); busy = false;
languageKey = 'en-GB'; assert.equal(write(pending, '変更').error.code, 'TARGET_CHANGED');
const english = read(token); assert.equal(english.text, 'A lighthouse.');
assert.equal(write(english, 'The lighthouse shines.').changed, true);
assert.equal(state.blocks[0].flow.document.sections[0].blocks[0].texts.ja, '手入力。');
languageKey = 'en-US'; const missing = read(token); assert.equal(missing.text, ''); assert.equal(missing.missingTranslation, true);
assert.equal(write(missing, 'New translation.').changed, true);
const latest = read(token); const snap = JSON.stringify(state.blocks);
assert.equal(write(latest, 'x\ny').error.code, 'LINE_BREAKS_CHANGED');
for (const text of ['x'.repeat(12001), 12]) assert.equal(write(latest, text).error.code, 'INVALID_ARGUMENTS');
assert.equal(JSON.stringify(state.blocks), snap);
activeGroupId = 'another'; assert.equal(write(latest, 'x').error.code, 'TARGET_CHANGED'); activeGroupId = 'g';
readonly.disable(); assert.equal(write(latest, 'x').error.code, 'DISABLED');
readonly.enable(); assert.equal(write(latest, 'x').error.code, 'STALE_WORK_TOKEN');
const newToken = readonly.execute('dsf_get_editor_context', {}).workToken, switched = read(newToken);
identity = {}; assert.equal(write(switched, 'x').error.code, 'WORK_CHANGED');
// Shared semantic update preserves unaffected ruby/emphasis, other languages and block identity.
const group = make(); group.flow.document.schemaVersion = 2;
const b = group.flow.document.sections[0].blocks[0];
b.annotations = { ja: [{ id: 'ruby', type: 'ruby', start: 0, end: 2, reading: 'とうだい', reviewState: 'confirmed' }, { id: 'dot', type: 'emphasis', start: 0, end: 2, mark: 'dot' }] };
const target = { groupId: 'g', sectionId: 's', blockId: 'p', languageKey: 'ja' };
const edited = editFlowParagraph([group], target, '灯台の光。', '灯台の明かり。').blocks[0];
assert.deepEqual(edited.flow.document.sections[0].blocks[0].annotations, b.annotations);
assert.equal(edited.flow.document.sections[0].blocks[0].texts['en-GB'], 'A lighthouse.');
assert.ok(edited.flow.translationState);
const unicode = editFlowParagraph([make()], target, '灯台の光。', '👩‍👩‍👧‍👦とéの灯台。');
assert.equal(unicode.blocks[0].flow.document.sections[0].blocks[0].texts.ja, '👩‍👩‍👧‍👦とéの灯台。');
assert.equal(group.flow.document.sections[0].blocks[0].texts.ja, '灯台の光。');
const changedRuby = editFlowParagraph([group], target, '灯台の光。', '灯塔の光。').blocks[0].flow.document.sections[0].blocks[0];
assert.equal(changedRuby.annotations.ja[0].reviewState, 'needs-review');
// Pasted manuscripts can contain all visible lines inside one semantic paragraph.
readonly.disable(); identity = {}; languageKey = 'ja'; state.blocks = [make()]; clearHistory();
const multiline = '灯台のある町\n\n海辺の町に、小さな灯台がありました。\n\n夕暮れになると、灯台の光。遠くの船を静かに照らします。\n\n少年は港で、その光を眺めていました。\n\n明日も、この町には穏やかな朝が訪れるでしょう。';
state.blocks[0].flow.document.sections[0].blocks[0].texts.ja = multiline;
const multilineBefore = JSON.stringify(state.blocks), commitsBefore = commits;
readonly.enable(); const multi = read(readonly.execute('dsf_get_editor_context', {}).workToken);
const replacement = multiline.replace('灯台の光。', '灯台の明かり。');
for (const text of [replacement.replace(/\n/g, ''), replacement + '\n', replacement.replace('\n', '\r\n')]) {
    assert.equal(write(multi, text).error.code, 'LINE_BREAKS_CHANGED');
    assert.equal(JSON.stringify(state.blocks), multilineBefore);
}
assert.equal(write(multi, replacement).changed, true); assert.equal(commits, commitsBefore + 1);
assert.equal(state.blocks[0].flow.document.sections[0].blocks.length, 1);
assert.equal(state.blocks[0].flow.document.sections[0].blocks[0].texts.ja, replacement);
assert.equal(state.blocks[0].flow.document.sections[0].blocks[0].texts['en-GB'], 'A lighthouse.');
assert.equal(read(multi.workToken).text, replacement);
undo(() => {}); assert.equal(JSON.stringify(state.blocks), multilineBefore);
redo(() => {}); assert.equal(state.blocks[0].flow.document.sections[0].blocks[0].texts.ja, replacement);
for (const separator of ['\n', '\r\n', '\r', '\u2028', '\u2029']) {
    const g = make(), original = '前の行' + separator + '灯台の光。' + separator + '後の行';
    g.flow.document.sections[0].blocks[0].texts.ja = original;
    const updated = original.replace('光', '明かり');
    assert.equal(editFlowParagraph([g], target, original, updated).blocks[0].flow.document.sections[0].blocks[0].texts.ja, updated);
    assert.throws(() => editFlowParagraph([g], target, original, updated + separator), { code: 'LINE_BREAKS_CHANGED' });
}
console.log('Write tools passed: exact target, stale/replay/revoke guards, Unicode text, translations, annotations, Undo/Redo and one history step.');
