import assert from 'node:assert/strict';
import {normalizeBookSpineDesign, getBookSpinePresentation} from '../js/book-spine-design.js';
import {normalizeBookSettings} from '../js/page-labels.js';
import {prepareProjectForSave, hydrateProjectFromPersistence} from '../js/project-persistence.js';
const design={title:'潮騒の図書館',author:'山口哲史',backgroundColor:'#224466',textColor:'#fffefe',fontSize:18};
assert.equal(normalizeBookSpineDesign(null),null);
assert.equal(normalizeBookSpineDesign({backgroundColor:'url(https://invalid)',textColor:'red',fontSize:100}).backgroundColor,'#173d42');
assert.equal(normalizeBookSpineDesign({fontSize:100}).fontSize,24);
assert.equal(normalizeBookSpineDesign({fontSize:-10}).fontSize,6);
assert.equal(normalizeBookSpineDesign({title:'x'.repeat(121)}).title.length,120);
assert.deepEqual(normalizeBookSettings({mode:'full',spineDesign:design},'full',8).spineDesign,design);
assert.equal(getBookSpinePresentation(null,{title:'Old title',author:'Old author'}).author,'Old author');
assert.equal(getBookSpinePresentation({}, {title:'題名',author:'著者'}).author,'著者');
assert.equal(getBookSpinePresentation(null).fontSize,18);
assert.equal(getBookSpinePresentation(null).thickness,32);
assert.equal(getBookSpinePresentation(null,{publisherName:'山口出版'}).publisherName,'山口出版');
assert.equal(normalizeBookSpineDesign({publisherIcon:'https://example.com/icon.png'}).publisherIcon,undefined);
assert.equal(normalizeBookSpineDesign({publisherName:'x'.repeat(90)}).publisherName.length,80);
const old=normalizeBookSettings({mode:'full'},'full',8);
assert.equal(Object.hasOwn(old,'spineDesign'),false,'old projects should not acquire decoration on load');
const project=prepareProjectForSave({version:5,book:{...old,spineDesign:design},blocks:[{id:'page_one',kind:'page',content:{pageKind:'image',background:''}}],languages:['ja'],defaultLang:'ja'});
const restored=hydrateProjectFromPersistence(JSON.parse(JSON.stringify(project)));
assert.deepEqual(restored.book.spineDesign,design);
console.log('Physical spine defaults, input bounds and authoring persistence passed.');

const {loadBookSpinePublisher} = await import('../js/book-spine-publisher.js');
const catalogue = {uid:'owner', spaces:[{id:'assigned',name:'山口出版',profile:{icon:'hash'}},{id:'selected',name:'別の出版社'}],assignments:{book:'assigned'}};
const calls=[];
const request = async command => {calls.push(command);return command ? {uid:'owner',dataUrl:'data:image/webp;base64,AAAA'} : catalogue;};
assert.deepEqual(await loadBookSpinePublisher({projectId:'book',uid:'owner',request}),{name:'山口出版',icon:'data:image/webp;base64,AAAA'});
assert.equal(calls[1].spaceId,'assigned');
catalogue.spaces[0].name='更新された出版社';
assert.equal((await loadBookSpinePublisher({projectId:'book',uid:'owner',request})).name,'更新された出版社');
assert.deepEqual(await loadBookSpinePublisher({projectId:'personal',uid:'owner',request}),{name:'',icon:''});
await assert.rejects(loadBookSpinePublisher({projectId:'book',uid:'owner',request,isCurrent:()=>false}),/AUTH_CHANGED/);
await assert.rejects(loadBookSpinePublisher({projectId:'book',uid:'wrong',request}),/AUTH_CHANGED/);
await assert.rejects(loadBookSpinePublisher({projectId:'book',uid:'owner',request:async command=>{if(command)throw Error('offline');return catalogue;}}),/offline/);
assert.equal(normalizeBookSpineDesign({publisherSource:'space'}).publisherSource,'space');
console.log('Assigned-space lookup, profile refresh, private space omission, identity guard and image failures passed.');
