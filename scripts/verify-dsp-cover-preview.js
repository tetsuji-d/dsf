import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import JSZip from 'jszip';
import {createDspCoverPreview, addDspCoverPreview, selectDspCoverSection} from '../js/dsp-cover-preview.js';
const project={defaultLang:'ja',blocks:[{kind:'page'}],sections:[{type:'image',background:'cover'}]};
let guard='one',calls=0;
const png=new Blob(['test PNG'],{type:'image/png'});
const options={project,guard,readGuard:()=>guard,render:async()=>{calls++;return new Blob(['webp']);},encode:async()=>png};
assert.equal(await createDspCoverPreview(options),png);
assert.equal(calls,1);
guard='two';
assert.equal(await createDspCoverPreview(options),null);
assert.equal(calls,1);
guard='one';
assert.equal(await createDspCoverPreview({...options,render:async()=>{guard='two';return new Blob(['changed']);}}),null);
guard='one';
assert.equal(await createDspCoverPreview({...options,render:async()=>{throw Error('offline');}}),null);
assert.equal(await createDspCoverPreview({...options,encode:async()=>new Blob(['wrong'],{type:'image/webp'})}),null);
assert.equal(await createDspCoverPreview({...options,encode:async()=>new Blob([new Uint8Array(1024*1024+1)],{type:'image/png'})}),null);
assert.equal(selectDspCoverSection({...project,blocks:[{kind:'flow'},...project.blocks]}),null);
assert.equal(selectDspCoverSection({...project,sections:[{type:'image',bubbles:[{}]}]}),null);
let finish;
assert.equal(await createDspCoverPreview({...options,timeoutMs:5,render:()=>new Promise(resolve=>{finish=resolve;})}),null);
const oldCalls=calls;
assert.equal(await createDspCoverPreview(options),null); // no accumulating late render jobs
assert.equal(calls,oldCalls);
finish(new Blob(['late']));
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(await createDspCoverPreview(options),png);
const zip=new JSZip();
const projectJson=JSON.stringify(project);
zip.file('project.json',projectJson);
const hashBytes=async bytes=>createHash('sha256').update(bytes).digest('hex');
assert.equal(await addDspCoverPreview(zip,{png,projectJson,language:'ja',hashBytes}),true);
const read=await JSZip.loadAsync(await zip.generateAsync({type:'nodebuffer'}),{checkCRC32:true});
const info=JSON.parse(await read.file('preview/cover.json').async('string'));
assert.equal(info.sourceSha256,await hashBytes(Buffer.from(projectJson)));
assert.equal(info.imageSha256,await hashBytes(Buffer.from(await png.arrayBuffer())));
assert.equal(await read.file('project.json').async('string'),projectJson);
assert.deepEqual(Object.keys(read.files).sort(),['preview/cover.json','preview/cover.png','project.json']);
assert.equal(await addDspCoverPreview(zip,{png,projectJson,language:'ja',hashBytes:async()=>{throw Error('hash failed');}}),false);
assert.equal(zip.file('preview/cover.png'),null);
assert.equal(zip.file('preview/cover.json'),null);
assert.equal(await zip.file('project.json').async('string'),projectJson);
console.log('DSP cover preview: guarded rendering, timeout, optional failure and archive/source hashes passed.');
