import assert from 'node:assert/strict';
import {resolveUiLanguage,getPlatformLanguage,setPlatformLanguage,subscribePlatformLanguage,UI_LANGUAGE_KEY} from '../js/ui-language.js';
import {WORK_LANGUAGE_TARGETS,workLanguageName,workLanguageOptionLabel} from '../js/work-languages.js';
const store=new Map([['dsf_studio_ui_lang','ja'],['dsf_viewer_ui_lang','en'],['manuscript-language','zh-tw']]);
globalThis.localStorage={getItem:key=>store.get(key)||null,setItem:(key,value)=>store.set(key,value)};
globalThis.window=new EventTarget();
if(!globalThis.CustomEvent)globalThis.CustomEvent=class extends Event{constructor(type,{detail}){super(type);this.detail=detail;}};
assert.equal(resolveUiLanguage({shared:'ja',legacy:'en'}),'ja');
assert.equal(resolveUiLanguage({shared:'fr',legacy:'ja'}),'ja');
assert.equal(resolveUiLanguage({browserLanguages:['fr','ja-JP']}),'ja');
assert.equal(resolveUiLanguage({browserLanguages:['de']}),'en');
assert.equal(getPlatformLanguage('studio'),'ja');
assert.equal(getPlatformLanguage('viewer'),'ja','Shared preference wins over conflicting legacy surface');
const changes=[];const unsubscribe=subscribePlatformLanguage(value=>changes.push(value));
setPlatformLanguage('en');setPlatformLanguage('en');setPlatformLanguage('fr');
assert.deepEqual(changes,['en'],'No duplicate/unsupported notifications');
assert.equal(store.get('dsf_portal_lang'),'en');
assert.equal(store.get('manuscript-language'),'zh-tw','UI settings never write manuscript preferences');
store.set(UI_LANGUAGE_KEY,'ja');
const storageEvent=new Event('storage');Object.assign(storageEvent,{key:UI_LANGUAGE_KEY,newValue:'ja'});window.dispatchEvent(storageEvent);
assert.deepEqual(changes,['en','ja']);
unsubscribe();setPlatformLanguage('en');assert.equal(changes.length,2);
globalThis.localStorage={getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}};
setPlatformLanguage('ja');assert.equal(getPlatformLanguage('viewer'),'ja','Session preference works with blocked storage');
assert.equal(WORK_LANGUAGE_TARGETS.length,20);assert.equal(new Set(WORK_LANGUAGE_TARGETS.map(x=>x.code)).size,20);
assert.equal(workLanguageName('zh-cn'),'中国語（簡体字）');assert.equal(workLanguageName('zh-tw'),'中国語（繁体字）');
assert.equal(workLanguageName('en-us','en'),'English (US)');assert.equal(workLanguageName('en-gb','en'),'English (UK)');
assert.equal(workLanguageName('en','en'),'English');assert.equal(workLanguageOptionLabel('zh-tw'),'中国語（繁体字） · 繁體中文');
assert.equal(workLanguageName('bad_code_!'),'bad_code_!');
const stored=['en','en-us','en-gb','zh-cn','zh-tw'];const before=JSON.stringify(stored);stored.forEach(code=>workLanguageOptionLabel(code));assert.equal(JSON.stringify(stored),before);
console.log('PASS: shared UI preference, migration, cross-tab event, blocked storage, 20-language labels and legacy keys.');
