import assert from 'node:assert/strict';
import { createFlowGroupBlock } from '../js/flow-project-model.js';
import { isolateFlowTitlePage } from '../js/flow-title-page.js';
import { serializeProject,deserializeProject } from '../js/project-persistence.js';
const group=createFlowGroupBlock({id:'group',sourceLanguage:'ja',document:{sourceLanguage:'ja',sections:[{id:'s',title:{ja:'章'},blocks:[{id:'p',type:'paragraph',texts:{ja:'前半扉本文後半'}}]}]}});
const fragment=(start,end)=>({sectionId:'s',blockId:'p',languageKey:'ja',text:'前半扉本文後半'.slice(start,end),sourceRange:{start,end}});
const text=g=>g.flow.document.sections.flatMap(s=>s.blocks).map(b=>b.texts?.ja||'').join('');
const original=JSON.stringify(group);
const result=isolateFlowTitlePage([group],'group',{fragments:[fragment(2,5)]});
assert.equal(result.blocks.length,1);
assert.equal(result.blocks[0].id,group.id);
assert.equal(result.blocks[0].flow.document.id,group.flow.document.id);
assert.equal(text(result.blocks[0]),text(group));
assert.equal(result.blocks[0].flow.document.schemaVersion,3);
assert.deepEqual(result.blocks[0].flow.document.sections[0].blocks.map(b=>b.texts.ja),['前半','扉本文','後半']);
assert.equal(result.blocks[0].flow.document.sections[0].blocks[1].titleRegion.blockAlign,'center');
assert.equal(result.blocks[0].flow.document.sections[0].blocks[0].titleRegion,undefined);
assert.equal(JSON.stringify(group),original);
assert.deepEqual(deserializeProject(serializeProject({version:6,blocks:result.blocks,languages:['ja'],defaultLang:'ja'})).blocks,result.blocks);
const {paginateFlowDocument,createCanonicalFlowPageBox}=await import('../js/flow-pagination.js');
const {updateFlowTitleRegion}=await import('../js/flow-title-page.js');
const pages=paginateFlowDocument(result.blocks[0].flow.document,{languageKey:'ja',pageBox:createCanonicalFlowPageBox(),measurePage:()=>({fits:true})});
assert.deepEqual(pages.pages.map(p=>p.fragments.map(f=>f.text).join('')),['前半','扉本文','後半']);
const removed=updateFlowTitleRegion(result.blocks,group.id,result.regionId,{remove:true});
assert.equal(paginateFlowDocument(removed.blocks[0].flow.document,{languageKey:'ja',pageBox:createCanonicalFlowPageBox(),measurePage:()=>({fits:true})}).pages.length,1);
assert.equal(text(removed.blocks[0]),text(group));
for(const [start,end] of [[0,7],[0,2],[5,7]])assert.equal(isolateFlowTitlePage([group],'group',{fragments:[fragment(start,end)]}).blocks.length,1);
const translated=structuredClone(group);translated.flow.document.sections[0].blocks[0].texts.en='Translation';
assert.throws(()=>isolateFlowTitlePage([translated],'group',{fragments:[fragment(2,5)]}),e=>e.code==='translation');
assert.equal(isolateFlowTitlePage([translated],'group',{fragments:[fragment(0,7)]}).blocks[0].flow.document.sections[0].blocks[0].texts.en,'Translation');
assert.throws(()=>isolateFlowTitlePage([group],'group',{fragments:[{...fragment(2,5),text:'変更'}]}),e=>e.code==='stale');
assert.throws(()=>isolateFlowTitlePage([group],'group',{fragments:[{...fragment(2,5),languageKey:'en'}]}),e=>e.code==='source');
console.log('Title isolation: middle/first/last/full page, no empty groups, text preservation, translation protection, stale page rejection and persistence passed.');

const {createIncrementalFlowPaginator}=await import('../js/flow-incremental-pagination.js');
const paginator=createIncrementalFlowPaginator({pageBox:createCanonicalFlowPageBox(),languageKey:'ja',measurePage:()=>({fits:true})});
paginator.paginate(group.flow.document);
assert.deepEqual(paginator.paginate(result.blocks[0].flow.document).pagination.pages,pages.pages);
assert.equal(paginator.paginate(removed.blocks[0].flow.document).pagination.pages.length,1);
console.log('Title region: incremental add/remove agrees with cold pagination.');

const aligned=isolateFlowTitlePage([group],group.id,{fragments:[fragment(0,7)]},{initialAlignment:{textAlign:'end',blockAlign:'start'}});
assert.equal(aligned.blocks[0].flow.document.sections[0].blocks[0].titleRegion.textAlign,'end');
assert.equal(aligned.blocks[0].flow.document.sections[0].blocks[0].titleRegion.blockAlign,'start');
assert.equal(JSON.stringify(group),original);
console.log('Page alignment preserves the independently supplied axis; explicit title remains centered.');

const joined=isolateFlowTitlePage([group],group.id,{fragments:[fragment(0,2),fragment(2,7)]});
assert.equal(text(joined.blocks[0]),text(group));
assert.equal(joined.blocks[0].flow.document.sections[0].blocks.length,1);
assert.throws(()=>isolateFlowTitlePage([group],group.id,{fragments:[fragment(0,2),fragment(3,7)]}),e=>e.code==='stale');
console.log('Contiguous regions of one paragraph are accepted; missing source remains rejected.');

const {createGraphicObject}=await import('../js/graphic-object-model.js');
const wrapped=structuredClone(group);
wrapped.flow.layout.schemaVersion=2;
wrapped.flow.layout.anchoredObjects=[{id:'object',anchorBlockId:'p',wrap:'square',gapEm:.75,graphic:createGraphicObject('shape','shape','ja')}];
assert.throws(()=>isolateFlowTitlePage([wrapped],group.id,{fragments:[fragment(0,2),fragment(2,7)]}),e=>e.code==='wrap');
assert.deepEqual(group,JSON.parse(original));
console.log('Wrapped title constraint is reported distinctly, with no source mutation.');
