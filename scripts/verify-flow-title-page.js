import assert from 'node:assert/strict';
import { createFlowGroupBlock } from '../js/flow-project-model.js';
import { isolateFlowTitlePage } from '../js/flow-title-page.js';
import { serializeProject,deserializeProject } from '../js/project-persistence.js';
const group=createFlowGroupBlock({id:'group',sourceLanguage:'ja',document:{sourceLanguage:'ja',sections:[{id:'s',title:{ja:'章'},blocks:[{id:'p',type:'paragraph',texts:{ja:'前半扉本文後半'}}]}]}});
const fragment=(start,end)=>({sectionId:'s',blockId:'p',languageKey:'ja',text:'前半扉本文後半'.slice(start,end),sourceRange:{start,end}});
const text=g=>g.flow.document.sections.flatMap(s=>s.blocks).map(b=>b.texts?.ja||'').join('');
const original=JSON.stringify(group);
const result=isolateFlowTitlePage([group],'group',{fragments:[fragment(2,5)]});
assert.deepEqual(result.blocks.map(text),['前半','扉本文','後半']);
assert.equal(result.activeBlockIndex,1);
assert.equal(result.blocks[1].flow.pageRole,'title');
assert.equal(result.blocks[1].flow.layout.typographyByLanguage.ja.blockAlign,'center');
assert.equal(result.blocks[0].flow.layout.typographyByLanguage.ja.blockAlign,undefined);
assert.equal(result.blocks[2].flow.layout.typographyByLanguage.ja.blockAlign,undefined);
assert.equal(JSON.stringify(group),original);
assert.deepEqual(deserializeProject(serializeProject({version:6,blocks:result.blocks,languages:['ja'],defaultLang:'ja'})).blocks,result.blocks);
assert.equal(isolateFlowTitlePage([group],'group',{fragments:[fragment(0,7)]}).blocks.length,1);
assert.equal(isolateFlowTitlePage([group],'group',{fragments:[fragment(0,2)]}).blocks.length,2);
assert.equal(isolateFlowTitlePage([group],'group',{fragments:[fragment(5,7)]}).blocks.length,2);
const translated=structuredClone(group);translated.flow.document.sections[0].blocks[0].texts.en='Translation';
assert.throws(()=>isolateFlowTitlePage([translated],'group',{fragments:[fragment(2,5)]}),e=>e.code==='translation');
assert.equal(isolateFlowTitlePage([translated],'group',{fragments:[fragment(0,7)]}).blocks[0].flow.document.sections[0].blocks[0].texts.en,'Translation');
assert.throws(()=>isolateFlowTitlePage([group],'group',{fragments:[{...fragment(2,5),text:'変更'}]}),e=>e.code==='stale');
assert.throws(()=>isolateFlowTitlePage([group],'group',{fragments:[{...fragment(2,5),languageKey:'en'}]}),e=>e.code==='source');
console.log('Title isolation: middle/first/last/full page, no empty groups, text preservation, translation protection, stale page rejection and persistence passed.');
