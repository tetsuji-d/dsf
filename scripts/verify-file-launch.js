import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createFileLaunchInbox} from '../js/file-launch.js';
const manifest=JSON.parse(readFileSync('public/studio.webmanifest','utf8'));
assert.deepEqual(manifest.file_handlers.map(h=>h.accept),[{'application/vnd.dsf.project+zip':['.dsp']},{'application/vnd.dsf.content+zip':['.dsf']}]);
assert.ok(manifest.file_handlers.every(h=>h.launch_type==='multiple-clients'));
assert.equal(manifest.launch_handler.client_mode,'navigate-new');
let reads=0,opens=[],blocked=true,release;
const handle=(name,read=async()=>({name}))=>({kind:'file',name,getFile:async()=>{reads++;return read();}});
const inbox=createFileLaunchInbox({extension:'.dsp',openFile:async f=>{if(blocked)throw Error('unsaved');opens.push(f.name);if(release)await new Promise(resolve=>release=resolve);}});
inbox.receive({files:[handle('first.DSP'),handle('second.dsp'),handle('wrong.dsf'),{kind:'directory'}]});
assert.equal(reads,0,'receiving does not read or replace a document');
assert.equal(inbox.read().items.length,3);
assert.equal(await inbox.open(1),false);assert.equal(inbox.read().items[0].error,'unsaved');assert.deepEqual(opens,[]);
blocked=false;assert.equal(await inbox.open(1),true);assert.deepEqual(opens,['first.DSP']);
assert.equal(await inbox.open(3),false);assert.equal(reads,2,'wrong extension is rejected before reading');
inbox.receive({files:[handle('denied.dsp',async()=>{throw Error('NotAllowedError');}),handle('bad.dsp',async()=>({name:'bad.dsf'}))]});
assert.equal(await inbox.open(4),false);assert.equal(await inbox.open(5),false);
assert.equal(inbox.read().items.find(i=>i.id===4).error,'open');
release=true;const pending=inbox.open(2);await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(inbox.read().busy,true);assert.equal(await inbox.open(2),false);inbox.remove(2);assert.ok(inbox.read().items.find(i=>i.id===2));
inbox.receive({files:[handle('next.dsp')]});release();await pending;release=null;
assert.ok(inbox.read().items.find(i=>i.name==='next.dsp'),'a later launch is retained during an open');
inbox.remove(3);assert.equal(inbox.read().items.some(i=>i.id===3),false);
console.log('PASS file launch: explicit opening, multiple files, unsaved protection, retry, access failure, type validation and serialization');
let safe=false,guardReads=0,guardOpens=0;
const guarded=createFileLaunchInbox({extension:'.dsp',beforeOpen:async()=>{if(!safe)throw Error('unsaved');},openFile:async()=>{guardOpens++;}});
guarded.receive({files:[handle('protected.dsp',async()=>{guardReads++;return {name:'protected.dsp'};})]});
assert.equal(await guarded.open(1),false);
assert.equal(guardReads,0,'unsaved manuscript is checked before accessing the received file');
assert.equal(guarded.read().items[0].error,'unsaved');
safe=true;assert.equal(await guarded.open(1),true);assert.equal(guardReads,1);assert.equal(guardOpens,1);
console.log('PASS file launch pre-read protection and retry');
