const block = { type:'paragraph', texts:{ja:converted.text}, annotations:{ja:converted.annotations} };
validateFlowAnnotations(block);
assert.deepEqual(converted.annotations.map(a=>converted.text.slice(a.start,a.end)), ['漢字','文字']);
