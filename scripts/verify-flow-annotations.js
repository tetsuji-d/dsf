const document = {schemaVersion:1,sourceLanguage:'ja',sections:[{id:'section',blocks:[{id:'body',type:'paragraph',texts:{ja:'漢字',en:'Kanji'},future:{keep:true}}]}]};
const original = JSON.stringify(document);
const edit = {sectionId:'section',blockId:'body',languageKey:'ja',expectedText:'漢字',action:'set',annotation:{id:'r',type:'ruby',start:0,end:2,reading:'かんじ'}};
const rubyDocument = createFlowAnnotationEdit(document,edit);
