import assert from 'node:assert/strict';
import {describeStudioWork,studioWorkText} from '../js/studio-work-status.js';
const base={open:true,title:'Example',identity:'one',canEdit:true};
assert.equal(describeStudioWork().blocked,false);
assert.equal(describeStudioWork({...base,local:true,file:{dirty:false,fileSaved:false}}).blocked,true,'untouched unsaved drafts are not silently discarded');
assert.equal(describeStudioWork({...base,local:true,file:{dirty:false,fileSaved:true}}).canClose,true);
assert.equal(describeStudioWork({...base,local:true,file:{dirty:true,fileSaved:true}}).blocked,true);
const restored=describeStudioWork({...base,local:true,file:{restored:true,dirty:false,fileSaved:false}});
assert.equal(restored.status,'restored');assert.equal(restored.blocked,true);assert.equal(restored.canClose,false);assert.match(studioWorkText(restored),/保存確認待ち/);
assert.equal(describeStudioWork({...base,save:{localCurrent:true,cloudCurrent:false}}).blocked,true,'backup is not cloud confirmation');
assert.equal(describeStudioWork({...base,save:{cloudCurrent:true}}).blocked,false);
assert.equal(describeStudioWork({...base,save:{cloudCurrent:true},busy:'uncommitted'}).blocked,true,'uncommitted input blocks reload');
assert.equal(describeStudioWork({...base,save:{state:'saving'}}).canSave,false);
assert.equal(describeStudioWork({...base,online:false}).status,'waiting');
assert.equal(describeStudioWork({...base,online:false}).canSave,false);
assert.equal(describeStudioWork({...base,online:false,local:true}).canSave,true);
assert.equal(describeStudioWork({...base,shared:true,canEdit:false}).canSave,false);
assert.equal(describeStudioWork({...base,shared:true,save:{cloudCurrent:true}}).canClose,false,'shared teardown uses existing lease flow');
assert.equal(describeStudioWork({...base,shared:true}).canExport,false);
assert.match(studioWorkText(describeStudioWork({...base,save:{state:'error',errorCode:'AUTHORING_CONFLICT'}})),/変更の確認/);
console.log('PASS current work: unsaved files, cloud evidence, pending input, offline, shared boundaries and conflicts');
