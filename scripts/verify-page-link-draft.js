import assert from 'node:assert/strict';
import { createPageLinkDraft, formatPageReference, validatePageLinkSelection } from '../js/page-link-draft.js';
const target = { kind: 'text', ownerId: 'flow', objectId: 'p', language: 'ja', text: '波の仕組み👩‍💻を読む', start: 0, end: 5 };
let source = target.text, number = 3, caption = '図の説明';
const model = createPageLinkDraft({ readTarget: t => t.kind === 'image' ? { caption, visible: true } : { text: source }, resolvePage: () => ({ number }), pages: () => [{ number: 1 }, { number: 3 }], id: () => 'a1' });
const original = JSON.stringify(target), a = model.register(target, '波');
assert.equal(JSON.stringify(target), original);
assert.equal(model.preview(target, { kind: 'anchor', anchorId: a.id }, 'paren').reference, '(p.3)');
number = 103;
assert.equal(model.preview(target, { kind: 'anchor', anchorId: a.id }, 'kanji').reference, '一〇三');
assert.equal(model.preview(target, { kind: 'page', pageNumber: 3 }, 'upper').reference, 'P. 3');
assert.throws(() => model.preview(target, { kind: 'page', pageNumber: 2 }, 'plain'), /UNRESOLVED/);
assert.throws(() => model.preview({ ...target, language: 'en' }, { kind: 'anchor', anchorId: a.id }, 'plain'), /UNRESOLVED/);
assert.throws(() => validatePageLinkSelection({ ...target, end: 6 }), /RANGE/);
source = '変更済み'; assert.equal(model.anchors()[0].page, null);
assert.throws(() => model.preview(target, { kind: 'anchor', anchorId: a.id }, 'plain'), /TARGET_CHANGED/);
const image = { kind: 'image', ownerId: 'page', objectId: 'image', language: 'ja' };
assert.equal(model.preview(image, { kind: 'page', pageNumber: 1 }, 'suffix').reference, '1頁');
caption = ''; assert.throws(() => model.setLink(image, { kind: 'page', pageNumber: 1 }, 'plain'), /CAPTION_REQUIRED/);
assert.deepEqual(['plain', 'lower', 'paren', 'upper', 'suffix', 'kanji'].map(f => formatPageReference(103, f)), ['103', 'p.103', '(p.103)', 'P. 103', '103頁', '一〇三']);
console.log('PASS page link UI draft: digit formats, exact ranges, stale source, language boundary, caption gate, anchor/absolute resolution');
