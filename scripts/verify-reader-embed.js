const docs=new Map([[`public_editions/${id}`,{authorUid:'owner',workId:'work',releaseId:'release',dsfStatus:'public',publication:{}}],
    [statePath,{revision:1,embedPolicy:{mode:'any',allowedOrigins:[]}}]]);
