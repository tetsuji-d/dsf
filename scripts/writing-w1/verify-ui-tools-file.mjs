import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {nodeRuntime} from './node-runtime.mjs';
import {loadDsfV3} from '../../js/dsf-writing-package.js';
import {penPixels,writingControlPoints} from '../../js/reader-writing-tools.js';
const path=process.argv[2];assert.ok(path,'Pass the DSF created by the tools UI acceptance run');
const h=await loadDsfV3(new Uint8Array(await readFile(path)),await nodeRuntime());
const all=h.envelope.document.pages.flatMap(p=>p.objects),pens=all.filter(o=>o.tool==='pen');
assert.equal(all.length,8);assert.equal(h.envelope.history.revisions.length,13);
assert.equal(pens.length,2);assert.deepEqual(pens.map(o=>o.baseWidth),[penPixels(.3),penPixels(.7)]);
assert.ok(pens.every(o=>o.color==='#d33544'));
const brush=all.find(o=>o.tool==='brush');assert.ok(new Set(brush.points.map(p=>p.width)).size>5);
assert.ok(brush.points.at(-1).width<brush.points.reduce((m,p)=>Math.max(m,p.width),0)*.3);
const correction=all.find(o=>o.tool==='correction');assert.equal(correction.color,'#ffffff');assert.equal(correction.opacity,1);
const shapes=all.filter(o=>o.type==='shape');assert.equal(shapes.length,2);assert.ok(shapes.every(o=>Math.abs(o.rect[2]-o.rect[3])<.01&&o.color==='#2363bc'));
const line=all.find(o=>o.type==='line');assert.equal(line.arrow,'both');
for(const end of [line.from,line.to])assert.ok(shapes.some(o=>writingControlPoints(o).some(p=>Math.hypot(p.x-end[0],p.y-end[1])<.01)));
const operations=h.envelope.history.revisions.map(r=>r.operation);assert.equal(operations.filter(s=>s==='ポイントを編集').length,2);
const result={ok:true,file:path,objects:all.length,history:operations.length,ballpointWidths:pens.map(o=>o.baseWidth),brushPoints:brush.points.length,shapes:shapes.map(o=>o.rect),line:{from:line.from,to:line.to,arrow:line.arrow},correction:true};
await writeFile(new URL('../../outputs/writing-w1/ui-tools-file-verification.json',import.meta.url),JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
