import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {registerPlatformLaunch,launchDestination} from '../js/platform-launch.js';
const base='https://example.test/studio?room=editor';
assert.equal(launchDestination('https://outside.test/',base),null);
assert.equal(launchDestination('javascript:alert(1)',base),null);
assert.equal(launchDestination('/upload',base),null);
assert.equal(launchDestination('/studio.html?room=editor&source=pwa',base),null);
assert.equal(launchDestination('/viewer?work=one',base),'https://example.test/viewer?work=one');
let consumer,count=0;const target={launchQueue:{setConsumer(fn){count++;consumer=fn;}}};
const urls=[],files=[];
registerPlatformLaunch('url',p=>urls.push(p.targetURL),target);
consumer({targetURL:'/viewer?work=one'});
consumer({files:[{name:'one.dsp'}],targetURL:'/studio'});
registerPlatformLaunch('file',p=>files.push(p.files[0].name),target);
consumer({files:[{name:'two.dsp'}]});
assert.equal(count,1);assert.deepEqual(urls,['/viewer?work=one']);assert.deepEqual(files,['one.dsp','two.dsp']);
const read=p=>readFileSync(p,'utf8');
assert.equal(JSON.parse(read('public/studio.webmanifest')).launch_handler.client_mode,'focus-existing');
const viewer=read('viewer.html');assert.ok(viewer.indexOf('id="viewer-app-menu-button"')<viewer.indexOf('id="viewer-horizon-link"'));
assert.ok(!read('js/platform-menu.js').includes("el.target='_blank'"));
assert.ok(read('studio.html').includes('studio-home-logo'));
assert.ok(read('js/app.js').includes('if(!work.blocked&&!work.busy)return true'));
console.log('PASS: same-window links, menu order, safe PWA URL routing and queued file launch coexistence.');
