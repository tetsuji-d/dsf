import assert from 'node:assert/strict';
import {localCopySpaceLabel as label} from '../js/home-local-space.js';
const project={projectId:'book_1',localOwnerUid:'owner_1'};
const catalogue={uid:'owner_1',spaces:[{id:'space_a',name:'山口出版'}],assignments:{book_1:'space_a'}};
const context={uid:'owner_1',catalogue,cloudProjectIds:new Set(['book_1','book_2'])};
assert.equal(label(project,context),'所属: 山口出版');
assert.equal(label({...project,projectId:'book_2'},context),'所属: マイスペース');
assert.equal(label({...project,projectId:'deleted'},context),'所属未確認');
assert.equal(label({...project,localOwnerUid:''},context),'所属未確認');
assert.equal(label(project,{...context,uid:'owner_2'}),'別アカウントの作業コピー');
assert.equal(label(project,{...context,catalogue:{...catalogue,uid:'owner_2'}}),'所属未確認');
assert.equal(label(project,{...context,online:false}),'所属未確認（オフライン）');
assert.equal(label(project,{...context,uid:''}),'所属確認にはログインが必要');
assert.equal(label({},context),'この端末のみ（スペース未所属）');
assert.equal(label(project,{...context,catalogue:{...catalogue,spaces:[]}}),'所属未確認');
assert.equal(label(project,{...context,catalogue:null}),'所属未確認');
assert.equal(label(project,{...context,locale:'en'}),'Space: 山口出版');
const moved={...catalogue,assignments:{}};
assert.equal(label(project,{...context,catalogue:moved}),'所属: マイスペース');
console.log('Local copy space labels: assignment, account, offline, deleted, missing and moved cases passed.');
