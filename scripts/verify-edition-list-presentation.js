import assert from 'node:assert/strict';
import { selectEditionRows, editionShareUrl } from '../js/edition-list-presentation.js';
const origin = 'https://staging.example.test';
const make = (id, title, label, date) => ({ title, sort: date, state: { editionId: 'e_' + id.repeat(64), editionLabel: label } });
const rows = [make('a', '図書館 ALPHA', '第10版', 100), make('b', '図書館 Alpha', '第2版', 200), make('c', '写真集', '', 0)];
const original = structuredClone(rows);
const select = options => selectEditionRows(rows, { origin, ...options });
assert.deepEqual(select({query:'図書館　ＡＬＰＨＡ 第２版'}), [rows[1]], 'NFKC, case and AND terms work together');
assert.equal(select({query:'見つからない'}).length,0);
assert.equal(select({query:'   '}).length,3);
assert.deepEqual(select({sort:'issued-asc'}), [rows[0],rows[1],rows[2]], 'unknown dates follow both ascending and descending dates');
assert.deepEqual(select({sort:'issued-desc'}), [rows[1],rows[0],rows[2]]);
assert.deepEqual(select({sort:'label-asc'}), [rows[1],rows[0],rows[2]], 'numeric edition labels sort naturally');
assert.deepEqual(select({sort:'label-desc'}), [rows[0],rows[1],rows[2]]);
const titles = [make('d','Title 10','',1),make('e','Title 2','',1)];
assert.deepEqual(selectEditionRows(titles,{sort:'title-asc',origin}), [titles[1],titles[0]]);
assert.deepEqual(selectEditionRows(titles,{sort:'title-desc',origin}), titles);
assert.deepEqual(select({sort:'invalid'}), select({sort:'issued-desc'}));
assert.deepEqual(rows,original,'search and sorting never change the input inventory');
const url = editionShareUrl(rows[0],origin);
assert.equal(new URL(url).searchParams.get('edition'), rows[0].state.editionId);
assert.deepEqual(select({query:rows[0].state.editionId}),[rows[0]],'search can identify an exact shared URL');
const old = {legacy:true,shareUrl:origin+'/viewer?work=old&r=original',state:{editionId:'legacy_0'}};
assert.equal(editionShareUrl(old,origin),old.shareUrl,'legacy URL is preserved exactly');
assert.equal(editionShareUrl({...old,shareUrl:''},origin),'','unconfirmed older URLs are not invented');
console.log('Edition presentation: search normalization, AND terms, date/title/edition sorting, unknown values, no mutation, fixed/legacy URLs passed.');
