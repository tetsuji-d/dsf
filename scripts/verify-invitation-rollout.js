import assert from 'node:assert/strict';
import {readInvitationRollout,createInvitationRolloutGuard} from '../server/publishing-invitations-rollout.js';
const scope={spaceId:'test_space',ownerUid:'owner',recipientUid:'reader',recipientHandle:'reader'};
assert.throws(()=>readInvitationRollout({}));
assert.throws(()=>readInvitationRollout({FIREBASE_PROJECT_ID:'vmnn-26345',PUBLISHING_INVITATIONS_TEST_SCOPE:JSON.stringify(scope)}));
assert.deepEqual(readInvitationRollout({FIREBASE_PROJECT_ID:'vmnn-26345-stg',PUBLISHING_INVITATIONS_TEST_SCOPE:JSON.stringify(scope)}),scope);
let reads=0;let invite={spaceId:scope.spaceId,inviterUid:'owner',recipientUid:'reader'};
const db={transaction:fn=>fn({getMany:async paths=>{reads++;return paths.map(p=>p.startsWith('publishing_spaces/')?{ownerUid:'owner'}:invite);}})};
const guard=createInvitationRolloutGuard({db,scope});
await assert.rejects(guard({uid:'stranger'},{kind:'inbox'}));
await assert.rejects(guard({uid:'reader'},{kind:'invite',spaceId:scope.spaceId,recipientUid:'reader'}));
await assert.rejects(guard({uid:'owner'},{kind:'invite',spaceId:'other',recipientUid:'reader'}));
await assert.rejects(guard({uid:'owner'},{kind:'invite',spaceId:scope.spaceId,recipientUid:'other'}));
await assert.rejects(guard({uid:'owner'},{kind:'resolveRecipient',spaceId:scope.spaceId,handle:'other'}));
assert.equal(reads,0);
await guard({uid:'owner'},{kind:'invite',spaceId:scope.spaceId,recipientUid:'reader'});
await guard({uid:'reader'},{kind:'inbox'});
await guard({uid:'reader'},{kind:'accept',id:'inv_1234567890123456'});
invite={...invite,spaceId:'other'};
await assert.rejects(guard({uid:'reader'},{kind:'accept',id:'inv_1234567890123456'}));
console.log('Invitation rollout scope: passed');

await guard({uid:'owner'},{kind:'getMemberAccess',spaceId:scope.spaceId,memberUid:'reader'});
await assert.rejects(guard({uid:'owner'},{kind:'setMemberAccess',spaceId:scope.spaceId,memberUid:'other'}));
await assert.rejects(guard({uid:'reader'},{kind:'setMemberAccess',spaceId:scope.spaceId,memberUid:'reader'}));
