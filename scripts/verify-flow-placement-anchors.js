import assert from 'node:assert/strict';
import {createFlowGroupBlock,validateFlowGroupBlock} from '../js/flow-project-model.js';
import {setFlowPagePlacement,resolvePagePlacement,validatePlacementPagination} from '../js/flow-page-placement.js';
import {applyFlowAuthoringOperation} from '../js/flow-authoring.js';
import {serializeProject,deserializeProject} from '../js/project-persistence.js';
import {joinFlowWithPrevious} from '../js/flow-group-join.js';
const group=createFlowGroupBlock({id:'g',sourceLanguage:'ja',document:{sourceLanguage:'ja',sections:[{id:'s',blocks:[{id:'p',type:'paragraph',texts:{ja:'前半後半本文',en:'original translation'}},{id:'q',type:'paragraph',texts:{ja:'続き',en:'next'}}]}]}});
const page=(blockId,start,end,languageKey='ja',isBlockEnd=false)=>({fragments:[{sectionId:'s',blockId,languageKey,text:group.flow.document.sections[0].blocks.find(b=>b.id===blockId).texts[languageKey].slice(start,end),sourceRange:{start,end},isBlockEnd}]});
const selected=page('p',2,6,'ja',true),before=structuredClone(group);
let blocks=setFlowPagePlacement([group],'g',selected,'ja','center').blocks;
assert.deepEqual(blocks[0].flow.document,before.flow.document);assert.equal(blocks[0].flow.layout.schemaVersion,4);
assert.equal(blocks[0].flow.layout.pagePlacements[0].utf16Offset,2);assert.ok(validateFlowGroupBlock(blocks[0]).valid);
assert.deepEqual(group,before);
blocks=setFlowPagePlacement(blocks,'g',page('p',0,20,'en',true),'en','end').blocks;
assert.equal(blocks[0].flow.layout.pagePlacements.length,2);
assert.deepEqual(deserializeProject(serializeProject({version:6,blocks})).blocks,blocks);
const op=(type,more)=>({type,groupId:'g',sectionId:'s',blockId:'p',languageKey:'ja',...more});
let changed=applyFlowAuthoringOperation(blocks,op('setText',{text:'追加前半後半本文'}));
assert.equal(changed[0].flow.layout.pagePlacements[0].utf16Offset,4);
assert.deepEqual(changed[0].flow.layout.pagePlacements[1],blocks[0].flow.layout.pagePlacements[1]);
changed=applyFlowAuthoringOperation(changed,op('setText',{text:'半本文'}));
assert.ok(changed[0].flow.layout.pagePlacements[0].utf16Offset<=3);
const split=applyFlowAuthoringOperation(blocks,op('splitParagraph',{utf16Offset:2,newBlockId:'tail'}));
assert.equal(split[0].flow.layout.pagePlacements[0].blockId,'tail');assert.equal(split[0].flow.layout.pagePlacements[0].utf16Offset,0);
assert.equal(split[0].flow.layout.pagePlacements[1].blockId,'p');
const joined=applyFlowAuthoringOperation(split,op('mergeParagraphBackward',{blockId:'tail'}));
assert.equal(joined[0].flow.layout.pagePlacements[0].blockId,'p');assert.equal(joined[0].flow.layout.pagePlacements[0].utf16Offset,2);
const more=setFlowPagePlacement(blocks,'g',page('q',0,2,'ja',true),'ja','end').blocks;
const combined={fragments:[...page('p',0,6,'ja',true).fragments,...page('q',0,2,'ja',true).fragments]};
assert.equal(resolvePagePlacement(more[0],combined,'ja').conflict,true);
assert.throws(()=>validatePlacementPagination(more[0],{languageKey:'ja',pages:[combined]}),e=>e.code==='FLOW_PLACEMENT_CONFLICT');
const resolved=setFlowPagePlacement(more,'g',combined,'ja','start').blocks;
assert.equal(resolvePagePlacement(resolved[0],combined,'ja').conflict,false);
assert.equal(resolved[0].flow.layout.pagePlacements.filter(a=>a.languageKey==='ja').length,1);
for(const version of [1,2,3,5]){const bad=structuredClone(blocks[0]);bad.flow.layout.schemaVersion=version;assert.equal(validateFlowGroupBlock(bad).valid,false);}
const bad=structuredClone(blocks[0]);bad.flow.layout.pagePlacements[0].utf16Offset=999;assert.equal(validateFlowGroupBlock(bad).valid,false);
const removed=applyFlowAuthoringOperation(blocks,op('removeBlock',{}));assert.equal(removed[0].flow.layout.pagePlacements.length,0);
console.log('Page placement v4: no text/translation split, language isolation, save/reload, text edit/split/merge/delete, conflict resolution and validation passed.');

const {placedFlowObject}=await import('../js/flow-page-placement.js');
const first={x:20,y:30,width:40,height:50,graphic:{frame:{x:20,y:30}}};
const second={x:70,y:40,width:20,height:30,graphic:{frame:{x:70,y:40}}};
const bundle={x:20,y:30,width:70,height:50,objects:[first,second],graphic:{members:[first.graphic,second.graphic]}};
const placed=placedFlowObject({anchoredObject:bundle,placementOffset:{x:5,y:80}});
assert.equal(placed.graphic.members[0].frame.y,110);assert.equal(placed.objects[0].graphic.frame.y,110);
assert.equal(first.graphic.frame.y,30);
const {isolateFlowTitlePage}=await import('../js/flow-title-page.js');
const titled=isolateFlowTitlePage(blocks,'g',page('p',0,6,'ja',true)).blocks;
assert.equal(titled[0].flow.layout.pagePlacements.length,0,'Title creation explicitly removes both language overrides on its text');
const unicode=structuredClone(blocks[0]);unicode.flow.document.sections[0].blocks[0].texts.ja='a\u0301b';unicode.flow.layout.pagePlacements[0].utf16Offset=1;
assert.equal(validateFlowGroupBlock(unicode).valid,false,'Anchors cannot bisect a grapheme');
console.log('Shared composite graphics translate once; title override cleanup and grapheme boundaries passed.');

const future=structuredClone(group);future.flow.layout.schemaVersion=5;
assert.throws(()=>setFlowPagePlacement([future],'g',selected,'ja','center'),e=>e.code==='FLOW_PLACEMENT_INVALID');
const {createFlowDirectEditSession}=await import('../js/flow-direct-edit.js');
const {createFlowImageInsertion}=await import('../js/flow-image-insertion.js');
const {createPageBlockFromSection}=await import('../js/blocks.js');
const session=createFlowDirectEditSession(blocks[0],{pageLanguageKey:'ja',writingMode:'vertical-rl',sourcePoint:{sectionId:'s',blockId:'p',languageKey:'ja',utf16Offset:2}});
const inserted=createFlowImageInsertion(blocks,session,{selectionStart:2,selectionEnd:2,expectedText:session.expectedText,imageBlock:createPageBlockFromSection({type:'image'})});
assert.equal(inserted.blocks[0].flow.layout.pagePlacements.length,1);
assert.equal(inserted.blocks[0].flow.layout.pagePlacements[0].languageKey,'en');
assert.equal(inserted.blocks[2].flow.layout.pagePlacements.length,1);
assert.equal(inserted.blocks[2].flow.layout.pagePlacements[0].utf16Offset,0);
const rejoined=joinFlowWithPrevious([inserted.blocks[0],inserted.blocks[2]],inserted.blocks[2].id);
assert.equal(rejoined.blocks[0].flow.layout.pagePlacements.length,2);
assert.ok(validateFlowGroupBlock(rejoined.blocks[0]).valid);
console.log('Flow split/join retains both language anchors; future layouts are never downgraded.');
