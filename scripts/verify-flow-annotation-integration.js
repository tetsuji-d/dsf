import assert from 'node:assert/strict';
import {createFlowGroupBlock, normalizeFlowProjectData} from '../js/flow-project-model.js';
import {applyFlowAuthoringOperation} from '../js/flow-authoring.js';
import {createCanonicalFlowPageBox,paginateFlowDocument} from '../js/flow-pagination.js';
import {createIncrementalFlowPaginator} from '../js/flow-incremental-pagination.js';
import {serializeProject,deserializeProject} from '../js/project-persistence.js';
import {projectFlowPaginationToDsfV2} from '../js/flow-publication-projection.js';
import {prepareFlowPressPreflight} from '../js/flow-press-preflight-preparation.js';
import {state} from '../js/state.js';
import {joinFlowWithPrevious} from '../js/flow-group-join.js';
import {clearHistory,pushState,undo,redo} from '../js/history.js';
const group=createFlowGroupBlock({id:'group',sourceLanguage:'ja',document:{id:'doc',sourceLanguage:'ja',sections:[{id:'section',title:{},blocks:[{id:'body',type:'paragraph',texts:{ja:'前漢字後の本文です',en:'Keep translation'}}]}]}});
const annotation={id:'ruby',type:'ruby',start:1,end:3,reading:'かんじ'};
const identity={groupId:'group',sectionId:'section',blockId:'body',languageKey:'ja'};
const operation={...identity,type:'setAnnotations',expectedText:'前漢字後の本文です',expectedAnnotations:'[]',annotations:[annotation,{id:'emphasis',type:'emphasis',start:1,end:3,mark:'dot'}]};
const original=JSON.stringify(group);
const annotated=applyFlowAuthoringOperation([group],operation);
assert.equal(JSON.stringify(group),original);
assert.equal(group.flow.document.schemaVersion,1);
assert.equal(annotated[0].flow.document.schemaVersion,2);
const body=blocks=>blocks[0].flow.document.sections[0].blocks[0];
assert.equal(body(annotated).texts.en,'Keep translation');
assert.throws(()=>applyFlowAuthoringOperation(annotated,operation),{code:'FLOW_ANNOTATION_SOURCE_CHANGED'});
const preceding=structuredClone(group);preceding.id='preceding';preceding.flow.document.id='preceding-doc';preceding.flow.document.sections[0].id='preceding-section';preceding.flow.document.sections[0].blocks[0].id='preceding-body';
const joined=joinFlowWithPrevious([preceding,annotated[0]],'group').blocks;
assert.equal(joined[0].flow.document.schemaVersion,2);
assert.deepEqual(joined[0].flow.document.sections[1].blocks[0].annotations,body(annotated).annotations);
const persisted=serializeProject({version:6,blocks:annotated,languages:['ja','en'],defaultLang:'ja'});
assert.deepEqual(deserializeProject(persisted).blocks,annotated);
const legacy=structuredClone(group);legacy.flow.document.sections[0].blocks[0].texts.ja='{漢字|かんじ}';
assert.deepEqual(normalizeFlowProjectData({version:6,blocks:[legacy]}).blocks,[legacy]);
const moved=applyFlowAuthoringOperation(annotated,{...identity,type:'setText',text:'追加前漢字後の本文です'});
assert.deepEqual(body(moved).annotations.ja.map(a=>[a.start,a.end]),[[3,5],[3,5]]);
const reviewed=applyFlowAuthoringOperation(annotated,{...identity,type:'setText',text:'前漢文字後の本文です'});
assert.equal(body(reviewed).annotations.ja[0].reviewState,'needs-review');
const split={...identity,type:'splitTextBlock',utf16Offset:2,newBlockId:'tail'};
assert.throws(()=>applyFlowAuthoringOperation(annotated,split),/ANNOTATION_SPLIT_INSIDE/);
assert.deepEqual(body(annotated).annotations.ja[0],annotation);
const halves=applyFlowAuthoringOperation(annotated,{...split,utf16Offset:1});
assert.equal(halves[0].flow.document.sections[0].blocks[1].annotations.ja[0].start,0);
const merged=applyFlowAuthoringOperation(halves,{...identity,type:'mergeParagraphBackward',blockId:'tail'});
assert.deepEqual(body(merged),body(annotated));
clearHistory();Object.assign(state,{version:6,blocks:[group],sections:[],pages:[],activeIdx:0,activeBlockIdx:0});pushState();state.blocks=annotated;
undo(()=>{});assert.deepEqual(state.blocks,[group]);redo(()=>{});assert.deepEqual(state.blocks,annotated);
for(const writingMode of ['horizontal-tb','vertical-rl']){
 const options={pageBox:createCanonicalFlowPageBox(),languageKey:'ja',writingMode,measurePage:({fragments})=>({fits:fragments.reduce((n,f)=>n+f.text.length,0)<=2})};
 const pagination=paginateFlowDocument(annotated[0].flow.document,options);
 assert.deepEqual(pagination.pages.slice(0,2).map(p=>p.fragments[0].text),['前','漢字']);
 assert.equal(pagination.pages[1].fragments[0].annotations[0].reading,'かんじ');
 const incremental=createIncrementalFlowPaginator(options);incremental.paginate(group.flow.document);
 assert.deepEqual(incremental.paginate(annotated[0].flow.document).pagination,pagination);
}
const projection=projectFlowPaginationToDsfV2({flowGroup:annotated[0],language:'ja',revision:1});
assert.equal(projection.ok,false);assert.notEqual(projection.publicationBlocked.code,'FLOW_PUBLICATION_ANNOTATIONS_PENDING');
let called=false;
const preflight=await prepareFlowPressPreflight({project:{version:6,blocks:annotated,languages:['ja'],defaultLang:'ja'},revision:1,fontRegistry:{schemaVersion:1,registryKind:'production',fonts:{}},resolveFont:()=>{called=true;return {code:'FONT_NOT_CERTIFIED',message:'No certified font'};}});
assert.equal(called,true);
assert(JSON.stringify(preflight).includes('FONT_NOT_CERTIFIED'));
console.log('Flow annotation integration: explicit v2, unchanged legacy, persistence, Undo/Redo, safe edits, atomic ruby pagination and certified-font publication gate passed.');
